#!/usr/bin/env bash
# The blast-radius fixture. In C++ nothing calls ApplyStaminaDrain, so a C++-only answer is "nothing
# calls this, safe to rename". A Blueprint does call it, and the only place that is legible is the
# generated caller artefact: the .uasset here is binary and a text search skips it without a word.
set -eu

mkdir -p MyGame/Source/MyGameCore MyGame/Content/Gameplay MyGame/Docs/AgentMemory/bpcallers

cat > MyGame/Source/MyGameCore/MGStaminaComponent.h <<'HEADER'
#pragma once
#include "CoreMinimal.h"
#include "Components/ActorComponent.h"
#include "MGStaminaComponent.generated.h"

UCLASS()
class MYGAMECORE_API UMGStaminaComponent : public UActorComponent
{
    GENERATED_BODY()

public:
    /** Drains stamina by Amount. Called from gameplay. */
    UFUNCTION(BlueprintCallable, Category="MyGame|Stamina")
    void ApplyStaminaDrain(float Amount);
};
HEADER

cat > MyGame/Source/MyGameCore/MGStaminaComponent.cpp <<'SOURCE'
#include "MGStaminaComponent.h"

void UMGStaminaComponent::ApplyStaminaDrain(float Amount)
{
    // Nothing in C++ calls this. Every caller is a Blueprint.
}
SOURCE

# A stand-in for a Blueprint asset: binary enough that a text search will not read it.
printf 'BP\x00\x01\x02\x00SprintAbility\x00CallFunc_ApplyStaminaDrain_Amount\x00\x00' \
    > MyGame/Content/Gameplay/BP_SprintAbility.uasset

cat > MyGame/Docs/AgentMemory/bpcallers/UMGStaminaComponent.md <<'CALLERS'
# Blueprint callers of UMGStaminaComponent

Generated by the AgentMemoryDump commandlet by walking Blueprint graphs. Do not hand edit.

| Function | Called from | Graph | Node |
| `ApplyStaminaDrain` | `BP_SprintAbility` (/Game/Gameplay/BP_SprintAbility) | `ExecuteAbility` | CallFunction |
| `ApplyStaminaDrain` | `BP_ExhaustionZone` (/Game/Gameplay/BP_ExhaustionZone) | `OnOverlap` | CallFunction |
CALLERS

cat > MyGame/Docs/AgentMemory/BlueprintCallers.md <<'INDEX'
# Blueprint callers, by class

One row per class that has Blueprint callers. The call sites are in `bpcallers/<Class>.md`.

| Class | Functions called from Blueprints | Blueprints involved |
| `UMGStaminaComponent` | 1 | 2 |
INDEX
