#!/usr/bin/env bash
# Builds the smallest tree that can tell the two routes apart: a header that does not carry the answer,
# a .cpp that does but only in runtime code, and a generated artefact that states it plainly.
set -eu

mkdir -p MyGame/Source/MyGameCore MyGame/Docs/AgentMemory/classes

cat > MyGame/Source/MyGameCore/MGStaminaComponent.h <<'HEADER'
#pragma once
#include "CoreMinimal.h"
#include "Components/ActorComponent.h"
#include "MGStaminaComponent.generated.h"

UCLASS(ClassGroup=(MyGame), meta=(BlueprintSpawnableComponent))
class MYGAMECORE_API UMGStaminaComponent : public UActorComponent
{
    GENERATED_BODY()

public:
    UMGStaminaComponent();

    /** Current stamina, 0 to 100. */
    UPROPERTY(Replicated, BlueprintReadOnly, Category="MyGame|Stamina")
    float Stamina = 100.0f;

    /** Whether the owner is sprinting. */
    UPROPERTY(Replicated, BlueprintReadOnly, Category="MyGame|Stamina")
    bool bSprinting = false;
};
HEADER

cat > MyGame/Source/MyGameCore/MGStaminaComponent.cpp <<'SOURCE'
#include "MGStaminaComponent.h"
#include "Net/UnrealNetwork.h"

UMGStaminaComponent::UMGStaminaComponent()
{
    PrimaryComponentTick.bCanEverTick = true;
    SetIsReplicatedByDefault(true);
}

void UMGStaminaComponent::GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const
{
    Super::GetLifetimeReplicatedProps(OutLifetimeProps);
    DOREPLIFETIME_CONDITION(UMGStaminaComponent, Stamina, COND_OwnerOnly);
    DOREPLIFETIME(UMGStaminaComponent, bSprinting);
}
SOURCE

cat > MyGame/Docs/AgentMemory/classes/UMGStaminaComponent.md <<'ARTEFACT'
